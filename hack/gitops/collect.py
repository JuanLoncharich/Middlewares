#!/usr/bin/env python3
# Turn what fake-kubectl.py recorded into one YAML file per namespace.
#   collect.py <record dir> <output dir>
# - Secrets are dropped (they never go to git; hack/gitops/secrets.sh).
# - An object applied twice keeps its last version, like kubectl apply.
# - `kubectl set env` calls become env changes on the matching Deployment.
# - Jobs get Flux's force annotation: their pod template is immutable, so a
#   changed Job is recreated (deploy.sh deletes and re-applies it).
# - Null fields are removed, as kubectl's client-side apply does. Flux's
#   server-side apply would send them (and fail validation, e.g. Chroma's
#   MemberList `members:`, which Chroma fills in at runtime).
# - Namespaces and PVCs are never pruned by Flux: deleting either would take
#   the hand-made Secrets or the vector data with it.
import json
import os
import shutil
import sys

import yaml

src, dst = sys.argv[1], sys.argv[2]
CLUSTER_SCOPED = {"Namespace", "CustomResourceDefinition", "ClusterRole", "ClusterRoleBinding",
                  "PriorityClass", "RuntimeClass", "ValidatingWebhookConfiguration",
                  "MutatingWebhookConfiguration", "StorageClass"}

def strip_nulls(v):
    if isinstance(v, dict):
        return {k: strip_nulls(x) for k, x in v.items() if x is not None}
    if isinstance(v, list):
        return [strip_nulls(x) for x in v]
    return v


objs = {}
order = []
with open(os.path.join(src, "manifests.jsonl")) as f:
    for line in f:
        rec = json.loads(line)
        for doc in yaml.safe_load_all(rec["yaml"]):
            if not doc:
                continue
            if doc.get("kind") == "List":
                items = doc.get("items") or []
            else:
                items = [doc]
            for d in map(strip_nulls, items):
                if d.get("kind") == "Secret":
                    continue
                md = d.setdefault("metadata", {})
                if d["kind"] not in CLUSTER_SCOPED and not md.get("namespace"):
                    md["namespace"] = rec["namespace"] or "default"
                if d["kind"] in CLUSTER_SCOPED:
                    md.pop("namespace", None)
                md.pop("creationTimestamp", None)
                key = (d["apiVersion"].split("/")[0] if "/" in d["apiVersion"] else "", d["kind"],
                       md.get("namespace", ""), md["name"])
                if key not in objs:
                    order.append(key)
                objs[key] = d

setenv = os.path.join(src, "setenv.jsonl")
if os.path.exists(setenv):
    with open(setenv) as f:
        for line in f:
            rec = json.loads(line)
            kind, name = rec["target"].split("/", 1)
            assert kind in ("deploy", "deployment", "deployments"), rec
            hits = [k for k in objs if k[1] == "Deployment" and k[3] == name and k[2] == (rec["namespace"] or "default")]
            if not hits:
                sys.exit(f"collect: set env on {rec['target']} in {rec['namespace']}: no such Deployment rendered")
            for k in hits:
                c = objs[k]["spec"]["template"]["spec"]["containers"][0]
                env = c.setdefault("env", [])
                for kv in rec["env"]:
                    n, v = kv.split("=", 1)
                    env[:] = [e for e in env if e.get("name") != n]
                    env.append({"name": n, "value": v})

FLUX_ANNOTATIONS = {
    "Job": {"kustomize.toolkit.fluxcd.io/force": "enabled"},
    "Namespace": {"kustomize.toolkit.fluxcd.io/prune": "disabled"},
    "PersistentVolumeClaim": {"kustomize.toolkit.fluxcd.io/prune": "disabled"},
}
for k in order:
    if k[1] in FLUX_ANNOTATIONS:
        md = objs[k]["metadata"]
        md["annotations"] = {**(md.get("annotations") or {}), **FLUX_ANNOTATIONS[k[1]]}

shutil.rmtree(dst, ignore_errors=True)
os.makedirs(dst)
files = {}
for k in order:
    fname = "_cluster.yaml" if k[1] in CLUSTER_SCOPED else f"{k[2]}.yaml"
    files.setdefault(fname, []).append(objs[k])
header = "# GENERATED by hack/gitops/render.sh from deploy.sh. Do not edit: change deploy.sh,\n# the manifests it applies or ../render.env, then re-render.\n"
for fname, docs in sorted(files.items()):
    with open(os.path.join(dst, fname), "w") as out:
        out.write(header)
        for d in docs:
            out.write("---\n")
            yaml.safe_dump(d, out, sort_keys=False, width=120)
with open(os.path.join(dst, "kustomization.yaml"), "w") as out:
    out.write(header)
    yaml.safe_dump({"apiVersion": "kustomize.config.k8s.io/v1beta1", "kind": "Kustomization",
                    "resources": sorted(files)}, out, sort_keys=False)
print(f"{len(order)} objects -> {len(files)} files (Secrets dropped)")
